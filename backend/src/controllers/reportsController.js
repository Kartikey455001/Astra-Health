/**
 * Reports Controller
 * Generates structured daily health reports, alert history, and export payloads.
 */

const store = require("../services/storeService");

function getDailyReport(req, res) {
  try {
    const astronautId = req.query.astronaut_id || store.state.astronauts[0].id;
    const summary = store.evaluateCrewMember(astronautId);
    const astro = summary.astronaut;

    const report = {
      mission_id: astro.mission_id,
      mission_day: Math.floor((Date.now() - new Date(store.state.missions[0].start_date).getTime()) / 86400000) + 1,
      generated_at: new Date().toISOString(),
      astronaut: {
        id: astro.id,
        name: astro.name,
        role: astro.role
      },
      overall_workflow_status: summary.overall,
      vitals_evaluation: summary.evals.map(e => ({
        metric: e.metric,
        label: store.state.health_baselines.find(b => b.astronaut_id === astro.id && b.metric === e.metric)?.metric || e.metric,
        latest_value: e.latest ? e.latest.value : null,
        unit: e.latest ? e.latest.unit : null,
        baseline: store.getBaseline(astro.id, e.metric),
        deviation_pct: e.deviation_pct !== null ? Number(e.deviation_pct.toFixed(1)) : null,
        severity: e.severity,
        quality_status: e.quality,
        data_origin: e.latest ? e.latest.data_origin : "NO_DATA",
        recorded_at: e.latest ? e.latest.recorded_at : null
      })),
      behavioral_evaluation: {
        severity: summary.behavioral.severity,
        explanation: summary.behavioral.explanation,
        recent_sleep_avg: (summary.behavioral.sleepLogs || []).reduce((acc, s) => acc + s.duration_hours, 0) / (summary.behavioral.sleepLogs?.length || 1)
      },
      open_alerts_count: store.state.alerts.filter(a => a.astronaut_id === astro.id && a.status === "open").length,
      provenance_statement: "Generated by ASTRA HEALTH. All crew telemetry in this environment carries data_origin tags (SIMULATED or MANUAL). Alert classes are prototype workflow categories from a deterministic rules engine using personal baselines — not clinical diagnostic thresholds."
    };

    res.json({ success: true, data: report });
  } catch (err) {
    res.status(500).json({ success: false, error: err.message });
  }
}

module.exports = {
  getDailyReport
};

