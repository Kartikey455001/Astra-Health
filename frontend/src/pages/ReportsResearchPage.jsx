import React, { useState } from "react";
import { useAstra } from "../store/astraStore";
import { api } from "../services/api";
import { METRICS } from "../utils/healthEngine";

export function ReportsResearchPage() {
  const { selectedAstro, astronauts, alerts, baselines, evaluateCrewMember, resetDemo } = useAstra();
  const [topic, setTopic] = useState("bone loss microgravity");
  const [libraryResults, setLibraryResults] = useState([]);
  const [libraryStatus, setLibraryStatus] = useState("Search to load live NASA records.");
  const [searching, setSearching] = useState(false);
  const [briefingOut, setBriefingOut] = useState("");
  const [briefingLoading, setBriefingLoading] = useState(false);

  const activeAstro = astronauts.find((a) => a.id === selectedAstro) || astronauts[0];
  const summary = evaluateCrewMember(selectedAstro);

  const handlePrint = () => {
    window.print();
  };

  const handleAiBriefing = async () => {
    setBriefingLoading(true);
    try {
      const res = await api.getDailyBriefingAi({
        astronaut_id: selectedAstro,
        model: "gemini-3.8-flash"
      });
      setBriefingOut(res.briefing || res.explanation || "Executive briefing compiled.");
    } catch (err) {
      setBriefingOut(`Executive briefing notice: ${err.message}`);
    } finally {
      setBriefingLoading(false);
    }
  };

  const handleSearchLibrary = async () => {
    setSearching(true);
    setLibraryStatus("Searching NASA OSDR and NTRS…");
    try {
      const res = await api.searchResearch(topic);
      if (res.results && res.results.length) {
        setLibraryResults(res.results);
        setLibraryStatus(`Live results — ${res.results.length} record(s) loaded.`);
      } else {
        setLibraryStatus("No records found for this topic.");
      }
    } catch (err) {
      setLibraryStatus(`Search error: ${err.message}`);
    } finally {
      setSearching(false);
    }
  };

  return (
    <section className="screen active">
      <div className="row row-between">
        <h2>Reports &amp; Research Library</h2>
        <div className="actions">
          <button onClick={handleAiBriefing} className="btn" disabled={briefingLoading}>
            {briefingLoading ? "Compiling Briefing…" : "✦ AI Executive Medical Briefing"}
          </button>
          <button onClick={handlePrint} className="btn">
            🖨 Print / save daily report as PDF
          </button>
          <button onClick={resetDemo} className="btn btn-ghost">
            Reset demo data
          </button>
        </div>
      </div>

      {(briefingLoading || briefingOut) && (
        <div className="assistant-out small" style={{ marginBottom: "14px" }}>
          {briefingLoading ? "Compiling AI Executive Medical Briefing with mission status and clinical evidence..." : briefingOut}
        </div>
      )}

      <div className="card">
        <h3>
          Daily Report — {activeAstro.name} · {new Date().toLocaleDateString()}
        </h3>
        <p>
          Overall workflow status: <strong>{summary.overall}</strong>
        </p>
        <table>
          <thead>
            <tr>
              <th>Metric</th>
              <th>Latest</th>
              <th>Baseline</th>
              <th>Deviation</th>
              <th>Status</th>
              <th>Origin</th>
            </tr>
          </thead>
          <tbody>
            {summary.evals.map((e) => {
              const b = baselines.find((x) => x.astronaut_id === selectedAstro && x.metric === e.metric)?.baseline_value || METRICS[e.metric]?.baseline;
              const devStr = e.deviation_pct === null ? "—" : `${e.deviation_pct >= 0 ? "+" : ""}${e.deviation_pct.toFixed(1)}%`;
              return (
                <tr key={e.metric}>
                  <td>{METRICS[e.metric]?.label}</td>
                  <td>{e.latest ? `${e.latest.value} ${e.latest.unit}` : "—"}</td>
                  <td>{b} {METRICS[e.metric]?.unit}</td>
                  <td>{devStr}</td>
                  <td>
                    <span className={`sev sev-${e.severity}`}>{e.severity}</span>
                  </td>
                  <td>
                    <span className={`tag tag-${e.latest?.data_origin === "SIMULATED" ? "sim" : "manual"}`}>
                      {e.latest?.data_origin || "NO_DATA"}
                    </span>
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>
        <p className="mt-3">
          <strong>Behavioral:</strong> {summary.behavioral.explanation}
        </p>
        <p className="fineprint">
          Generated by ASTRA HEALTH prototype. Simulated demo data; not a medical record. Alert classes are workflow categories from a deterministic rules engine using personal baselines — not NASA-approved medical thresholds.
        </p>
      </div>

      <div className="card">
        <h3>Alert History</h3>
        {alerts.length ? (
          <table>
            <thead>
              <tr>
                <th>When</th>
                <th>Crew</th>
                <th>Metric</th>
                <th>Severity</th>
                <th>Reasons</th>
              </tr>
            </thead>
            <tbody>
              {alerts.slice(-10).reverse().map((al) => {
                const who = astronauts.find((a) => a.id === al.astronaut_id);
                return (
                  <tr key={al.id}>
                    <td>{new Date(al.created_at).toLocaleString()}</td>
                    <td>{who?.name}</td>
                    <td>{al.metric}</td>
                    <td>
                      <span className={`sev sev-${al.severity}`}>{al.severity}</span>
                    </td>
                    <td>{typeof al.reason_codes === "string" ? al.reason_codes : JSON.stringify(al.reason_codes)}</td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        ) : (
          <p className="muted">No alerts recorded yet.</p>
        )}
      </div>

      <div className="card">
        <h3>
          NASA Research Library <span className="tag tag-nasa">NASA_PUBLIC</span>
        </h3>
        <div className="form-row">
          <label className="grow">
            Topic
            <input
              type="text"
              value={topic}
              onChange={(e) => setTopic(e.target.value)}
              placeholder="e.g. bone loss microgravity"
            />
          </label>
          <button onClick={handleSearchLibrary} className="btn" disabled={searching}>
            Search OSDR + NTRS
          </button>
        </div>
        <div className="muted mb-3">{libraryStatus}</div>

        <div>
          {libraryResults.map((r, i) => (
            <div key={i} className="research-item">
              <strong>{r.title}</strong> <span className="tag tag-nasa">NASA_PUBLIC</span>
              <br />
              <span className="muted">
                {r.source_name || r.source} · Accession {r.accession || r.source_record_id || "N/A"} · retrieved {new Date(r.retrieved_at || Date.now()).toLocaleTimeString()}
              </span>
              {r.description && <p className="mt-1 text-sm text-gray-300">{r.description}</p>}
              {r.source_url && (
                <a href={r.source_url} target="_blank" rel="noopener noreferrer">
                  Open source record ↗
                </a>
              )}
            </div>
          ))}
        </div>
      </div>
    </section>
  );
}

